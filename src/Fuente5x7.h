#define LETRA_N 0x7F, 0x02, 0x0C, 0x10, 0x7F
#define LETRA_O 0x3E, 0x41, 0x41, 0x41, 0x3E
#define LETRA_R 0x7F, 0x09, 0x19, 0x29, 0x46
#define LETRA_S 0x46, 0x49, 0x49, 0x49, 0x31
#define LETRA_T 0x01, 0x01, 0x7F, 0x01, 0x01
#define LETRA_V 0x0F, 0x30, 0x40, 0x30, 0x0F
#define LETRA_5 0x4F, 0x49, 0x49, 0x49, 0x31
#define LETRA_7 0x01, 0x01, 0x79, 0x05, 0x03

